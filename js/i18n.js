function detectLang() {
    const preferred =
        (navigator.languages && navigator.languages[0]) || navigator.language || 'en';
    return preferred.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export const lang = detectLang();
export const t = langPack[lang];
